// Writes bitcodex-spec/bitcodex-docs/ERRORS.md from the code (single source of truth):
// API error codes + HTTP status (backend/bitcodex_api_error_codes), SDK signing errors.
//   node scripts/gen_error_docs.mjs
import { readFileSync, writeFileSync } from "node:fs";

const api = readFileSync(
  "backend/bitcodex_api_error_codes/src/index.ts",
  "utf8",
);
const codes = [...api.matchAll(/^\s+([A-Z_0-9]+):\s*(\d{3}),/gm)].map((m) => [
  m[1],
  m[2],
]);
const bt = readFileSync(
  "sdk/bitcodex_sdk_core/src/types/modal/make_sig/bittensor.ts",
  "utf8",
);
const sigBlock = bt.slice(bt.indexOf("export type MakeBittensorSigError"));
const sigTypes = [
  ...sigBlock
    .slice(0, sigBlock.indexOf(";\n") + 1)
    .matchAll(/type: "([a-z_]+)"/g),
].map((m) => m[1]);

const meaning = {
  RATE_LIMIT_EXCEEDED:
    "Too many requests from this IP; retry after the window (Retry-After header).",
  INVALID_REQUEST: "The request body failed validation; `msg` names the field.",
  UNAUTHORIZED: "Missing credentials (API key or bearer token).",
  INVALID_AUTH_TOKEN:
    "Unknown or inactive API key, or an expired/invalid token.",
  FORBIDDEN: "Authenticated but not allowed (e.g. admin role required).",
  SIGNUP_DISABLED:
    "New wallets are disabled on this server (BITCODEX_SIGNUP_ENABLED).",
  FAUCET_DISABLED: "The faucet is off (localnet only).",
  FAUCET_NETWORK_REFUSED:
    "The faucet's chain is not localnet; nothing was sent.",
  FAUCET_TX_FAILED:
    "The faucet transfer failed on chain; `msg` has the decoded error.",
  UNKNOWN_ERROR: "Unexpected server error; safe to retry read-only calls.",
};
const sigMeaning = {
  unknown_error: "Unexpected failure while signing; `error` has details.",
  network_refused:
    "The request's network is not allowed (mainnet, unknown chain, or not this app's network).",
  signer_mismatch:
    "The payload is for a different account than the signed-in wallet.",
  origin_not_allowed:
    "The requesting site is not in the app's allowed origins (developer dashboard).",
};

let md =
  "# BitcodeX error codes\n\nGenerated by `node scripts/gen_error_docs.mjs` from the code. Do not edit by hand.\n\n";
md +=
  "## API (`{ success: false, code, msg }`)\n\n| Code | HTTP | Meaning |\n|---|---|---|\n";
for (const [code, status] of codes) {
  md += `| \`${code}\` | ${status} | ${meaning[code] ?? ""} |\n`;
}
md +=
  "\n## Signing popup (`open_modal_ack` error, `@bitcodex/sdk-bittensor` rejects with it)\n\n| `error.type` | Meaning |\n|---|---|\n";
for (const t of sigTypes) {
  md += `| \`${t}\` | ${sigMeaning[t] ?? "See MakeSigError in sdk-core."} |\n`;
}
md +=
  '\nThe user closing the popup rejects with `Error("Cancelled")` (`USER_CANCELLED`).\n';
md +=
  "\nChain errors are decoded by name (`section.Error`), e.g. `subtensorModule.SlippageTooHigh`, `swap.PriceLimitExceeded`, `proxy.NotProxy`, `system.CallFiltered`; a proxy call whose inner call fails rejects even though the outer extrinsic succeeded.\n";
writeFileSync("bitcodex-spec/bitcodex-docs/ERRORS.md", md);
console.log(
  `wrote ERRORS.md: ${codes.length} API codes, ${sigTypes.length} signing error types`,
);
