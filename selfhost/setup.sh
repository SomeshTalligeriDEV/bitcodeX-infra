#!/usr/bin/env bash
# BitcodeX self-host setup: generates every secret, asks only for the Google OAuth
# client ID (and the network), builds and starts the stack, prints the app ID + API key.
#   selfhost/setup.sh            first run (or re-run: keeps existing secrets)
#   selfhost/setup.sh --rebuild  rebuild images (e.g. after changing the client ID)
set -euo pipefail
cd "$(dirname "$0")/.."

ENV_FILE=selfhost/.env
SECRETS_DIR=selfhost/secrets
command -v docker >/dev/null || { echo "Docker is required."; exit 1; }
if docker compose version >/dev/null 2>&1; then
  COMPOSE=(docker compose)
elif command -v docker-compose >/dev/null; then
  COMPOSE=(docker-compose)
else
  echo "Docker Compose v2 is required (docker compose or docker-compose)."; exit 1
fi
COMPOSE+=(--env-file "$ENV_FILE" -f docker-compose.selfhost.yml)
# Without the buildx plugin, use Docker's classic builder (multi-stage targets still work).
if ! docker buildx version >/dev/null 2>&1; then
  export DOCKER_BUILDKIT=0 COMPOSE_DOCKER_CLI_BUILD=0
fi
command -v openssl >/dev/null || { echo "openssl is required."; exit 1; }

rand() { openssl rand -hex 32; }

if [[ ! -f "$ENV_FILE" ]]; then
  echo "BitcodeX self-host setup"
  echo
  echo "1) Google OAuth client ID (Google Cloud Console → Credentials → OAuth client, Web)."
  echo "   Authorized JavaScript origin: the iframe URL below (default http://localhost:3201)"
  echo "   Authorized redirect URI:      <iframe URL>/google/callback"
  read -r -p "   Google client ID: " GOOGLE_CLIENT_ID
  [[ "$GOOGLE_CLIENT_ID" == *.apps.googleusercontent.com ]] || {
    echo "That does not look like a Google OAuth client ID (…apps.googleusercontent.com)."; exit 1; }
  echo
  read -r -p "2) Network [testnet/localnet] (default testnet): " NET
  NET="${NET:-testnet}"
  case "$NET" in
    testnet) NETWORK=bittensor:testnet ;;
    localnet) NETWORK=bittensor:localnet ;;
    *) echo "Choose testnet or localnet (mainnet is disabled until an external audit)."; exit 1 ;;
  esac
  read -r -p "3) Your app's origin, e.g. http://localhost:3000 (Enter = allow any): " APP_ORIGINS

  umask 077
  mkdir -p "$SECRETS_DIR"
  chmod 700 "$SECRETS_DIR"
  rand > "$SECRETS_DIR/ksn_encryption_secret.txt"
  # Readable by the container user; the directory (700) keeps it private on this machine.
  chmod 644 "$SECRETS_DIR/ksn_encryption_secret.txt"
  {
    echo "# Generated by selfhost/setup.sh. Contains secrets: never commit or share."
    echo "GOOGLE_CLIENT_ID=$GOOGLE_CLIENT_ID"
    echo "GITHUB_CLIENT_ID="
    echo "GITHUB_CLIENT_SECRET="
    echo "BITCODEX_NETWORK=$NETWORK"
    echo "APP_ORIGINS=$APP_ORIGINS"
    echo "APP_LABEL=My BitcodeX app"
    echo "POSTGRES_PASSWORD=$(rand)"
    echo "JWT_SECRET=$(rand)"
    echo "API_ENCRYPTION_SECRET=$(rand)"
    echo "KS_NODE_REPORT_PASSWORD=$(rand)"
    echo "KSN_ADMIN_PASSWORD=$(rand)"
    echo "ACCESS_TOKEN_KEY=$(openssl genpkey -algorithm ed25519 | base64 | tr -d '\n')"
    echo "# Public URLs: what the browser uses. Change them when serving on a domain."
    echo "PUBLIC_API_URL=http://localhost:4200"
    echo "PUBLIC_KSN1_URL=http://localhost:4201"
    echo "PUBLIC_KSN2_URL=http://localhost:4202"
    echo "PUBLIC_IFRAME_URL=http://localhost:3201"
    echo "PUBLIC_DASHBOARD_URL="
    if [[ "$NETWORK" == bittensor:localnet ]]; then
      echo "# Localnet faucet: public dev account, localnet only."
      echo "FAUCET_SURI=//Alice"
      echo "FAUCET_RPC_URL=ws://host.docker.internal:9944"
    fi
  } > "$ENV_FILE"
  chmod 600 "$ENV_FILE"
  echo "Wrote $ENV_FILE (secrets not printed)."
fi

BUILD=(--build)
[[ "${1:-}" == "--no-build" ]] && BUILD=()
echo "Building and starting (the first build compiles the Rust signing code: 15-40 min)…"
"${COMPOSE[@]}" up -d "${BUILD[@]}" --wait postgres api ksn1 ksn2 iframe
echo "All services healthy."
"${COMPOSE[@]}" run --rm bootstrap

set -a; source "$ENV_FILE"; set +a
echo
echo "Wallet iframe (sdkEndpoint): $PUBLIC_IFRAME_URL"
echo "API:                         $PUBLIC_API_URL"
echo "Network:                     $BITCODEX_NETWORK"
echo "Stop:  ${COMPOSE[*]} down"
